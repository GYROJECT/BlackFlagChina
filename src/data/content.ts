我们也坚信（并正在实践中体现），这场冲突的革命视角在于：既不置身事外，也不自我稀释，而是认清我们在这一切中的角色。我知道，这是一个我们都懂的陈词滥调，但这具体意味着什么？具体意味着，我们只有在前往组织罢工的空间、与长期参与的人交谈、然后召开我们自己的会议并提出问题“这场罢工与我们的革命战略有何关系？”之后，才参与罢工。答案是：即时来看毫无关系，但潜力巨大。而在“即时不可能”与“潜在可能”之间的桥梁，正是革命工作的关键所在。必须由我们来构建这座桥梁。桥梁不会自行建成。
