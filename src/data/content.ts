国家以其纯粹形式出现，带着一般等价物的权力，是在简单商品生产时期价值规律增长的阶段。在资本的形式支配阶段，当资本尚未支配价值规律时，国家是资本与前资本主义生产方式残余之间的中介；无产阶级本身也仍带有这些残余。信用制度尚不发达，尚未大规模催生虚构资本。资本仍然需要刚性的金本位。随着向实质支配的过渡，资本创造了自己的一般等价物，它不可能像简单流通时期那样刚性。国家本身也必须失去其刚性，变成一个在不同帮派之间、在总资本与个别资本之间进行中介的帮派。

我们在政治领域可以看到类似的转变。政党的中央委员会或任何重组的中心扮演着与国家相同的角色。民主集中制仅仅模仿了形式支配时期特有的议会形式。而有机集中制，仅仅以否定方式被肯定，即作为对民主及其形式（少数服从多数、投票、代表大会等）的拒绝，实际上只是再次陷入更现代的形式之中。其结果便是组织的神秘化（如同法西斯主义那样）。意大利国际共产党就是这样演变成一个帮派的。

无产阶级既已被摧毁，资本的这一倾向在社会中便遇不到真正的对抗，因而能够更有效率地自我实现。无产阶级的真实本质遭到否认，它仅仅作为资本的一个客体而存在。同样，无产阶级的理论，即马克思主义，也已被摧毁：考茨基首先对它进行修正，随后伯恩施坦将其消解。这一过程以决定性的方式完成，因为此后无产阶级的任何冲击都未能使马克思主义得以重建。这不过是说，资本已经成功确立了其实质支配。为做到这一点，资本不得不吸收否定自身的运动，即无产阶级，并建立一种统一体，在其中无产阶级仅仅是资本的客体。这种统一体只能被危机所摧毁，正如马克思所描述的那些危机。由此，一切形式的工人阶级政治组织都已消失。取而代之的是，帮派彼此面对，展开一场淫秽的竞争；它们是名副其实的拉帮结派，在兜售之物上相互竞争，但在本质上却完全相同。

帮派的存在因而源于资本吸收其矛盾的倾向，源于其否定运动，以及其以虚构形式的再生产。资本否认，或倾向于否认，它据以建立自身的基本原则；但在现实中，它又以虚构形式使它们复活。帮派清晰地表达了这种二重性：

发号施令的老板＝传统个人及其小圈子的漫画式再现

集体形式＝基于共同利益的共同体的漫画式再现

否定运动于是被重新吸纳进帮派之中，而帮派正是表象的实现。帮派还满足了资本的另一个要求：它以由资本决定的前提，取代一切自然或人的前提。

在外部关系中，政治帮派倾向于掩盖小圈子的存在，因为它必须诱惑才能招募成员。它披上一层谦逊的面纱，以增强自身力量。当帮派通过期刊、杂志和传单向外部要素发出呼吁时，它认为自己必须站在大众的层面说话，以便被理解。它谈论直接之物，因为它想要中介。由于把帮派之外的每个人都视为愚昧者，它感到有义务出版平庸之论和胡言乱语，以便成功地诱惑他们。最终，它被自己的胡言乱语所诱惑，从而被周围环境所吸收。然而，另一个帮派会取而代之，而它最初的理论哀鸣，便是将一切恶行和错误归咎于它的前任，以此寻找一种新的语言，以便重新开始诱惑的伟大实践；为了诱惑，它必须显得与众不同。

一旦进入帮派，或任何类型的商业组织，个人便通过资本主义社会的一切心理依赖与之绑定。如果他表现出任何能力，这些能力会立即被剥削，而个人甚至没有机会掌握他所接受的“理论”。作为交换，他会在统治小圈子中获得一个位置，被塑造成一个小头目。如果他未能表现出能力，交换仍然会发生：以他加入帮派为代价，换取他传播帮派立场的义务。即使在那些试图逃避社会既定条件的团体中，帮派机制也仍倾向于占据主导，因为构成该团体的成员之间存在着不同程度的理论发展。无法独立面对理论问题，使个人不得不躲到另一位成员的权威背后，后者客观上成为领袖；或躲到团体实体背后，后者于是成为一个帮派。在与团体外的人的关系中，个人利用其成员身份排斥他人，并与他们区分开来，归根结底，这不过是为了保护自己，以免承认自身的理论弱点。为排斥而归属，这就是帮派的内在动力；它建立在团体外部与内部之间一种或明或暗的对立之上。即便一个非正式团体，也会蜕变为一个政治拉帮结派，这是理论变为意识形态的经典案例。

加入帮派的愿望，源于希望与一个体现某种声望的群体相认同：对知识分子而言是理论声望，对所谓务实之人而言是组织声望。商业逻辑也进入“理论”形成过程。随着有待实现的意识形态商品—资本总量不断增长，有必要创造一种深层动机，使人们购买商品。为此，最好的动机便是：多学、多读，以便居于其上，以便不同于大众。声望与排斥是一切形式竞争的标志；因此在这些帮派之间也是如此，它们必须夸耀自身的原创性和声望，以引起注意。这就是为什么对组织的崇拜以及对帮派特异性的颂扬得以发展。从那一刻起，问题不再在于捍卫一种“理论”，而在于保存一种组织传统，例如意大利国际共产党及其对意大利左派的偶像崇拜。

理论也常常被获取，用于政治操纵，例如支持自己获取领导地位的企图，或为罢免现任领袖辩护。

内外对立和帮派结构将竞争精神发展到极致。鉴于成员之间理论知识存在差异，理论的获取实际上成为一种政治自然选择的要素，即分工的一种委婉说法。当一方面人们在理论化现存社会时，另一方面，在团体内部，在以否定它为借口的情况下，一种无节制的竞相攀比被引入，最终导致一种比整个社会更为极端的等级化；尤其是因为内外对立在帮派中心与广大活动家之间的分工中，在内部被再次复制。

政治帮派在那些声称想要超越现存社会形式，如个人崇拜、领袖崇拜和民主崇拜的团体中达到其完善状态。在实践中，匿名性——仅仅被理解为反个人主义——意味着为方向小圈子的利益而对帮派成员进行无节制的剥削，该小圈子从帮派所生产的一切中获得声望。而有机集中制则沦为虚伪的实践，因为在那些声称实行民主集中制的团体中，无论如何都会出现两面派行为，尽管他们否认这一点。

维系帮派内部表面统一的是排斥的威胁。不遵守规范者会被诽谤所驱逐；即使他们自行退出，效果也是一样的。这种威胁也对留下的人构成心理勒索。同一过程在不同类型的帮派中以不同方式显现。

在商业帮派，即企业的现代形式中，个人被踢出门外，发现自己流落街头。

在青年帮派中，个人遭到殴打或被杀害。在这里，我们以原始形式发现反抗、犯罪；孤立的个人是软弱的，缺乏保护，因而被迫加入帮派。

在政治帮派中，个人被诽谤所排斥，而诽谤不过是暗杀的升华。诽谤为排斥他提供正当性，或被用来迫使他“出于自由意志”离开。

